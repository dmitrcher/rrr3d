#!/usr/bin/env python3
"""Export original chassis and every workshop tire curve to a C++98 fixture."""
from pathlib import Path
import hashlib
import xml.etree.ElementTree as E
ROOT=Path(__file__).resolve().parents[2]
DB=ROOT/'resources/game-data/db.xml'
WORKSHOP=ROOT/'resources/game-data/workshop.xml'

def generate():
    db=E.parse(DB).getroot().find('ctCar')
    workshop=E.parse(WORKSHOP).getroot().find('workshop')
    lines=['// Generated by export-catalog.py. Do not edit coefficients manually.', '// db.xml sha256: '+hashlib.sha256(DB.read_bytes()).hexdigest(), '// workshop.xml sha256: '+hashlib.sha256(WORKSHOP.read_bytes()).hexdigest(), 'inline void appendCatalogCases(std::vector<Case>& suite) {', ' Case c("catalog");']
    def vec(text):return 'V('+','.join(text.split())+')'
    def emit_tire(variable,node):
        for key,xml in [('extremumSlip','extremumSlip'),('extremumValue','extremumValue'),('asymptoteSlip','asymptoteSlip'),('asymptoteValue','asymptoteValue'),('stiffness','stiffnessFactor')]:
            lines.append(' '+variable+'.'+key+'='+node.findtext(xml,default='0')+';')
    for car in db:
        box=car.find('pxActor/shapes/items/item0');body=car.find('pxActor/body');name=car.tag
        lines.extend([' c=Case("catalog",-20,'+body.findtext('mass')+',15);c.catalog="'+name+'";', ' c.halfExtents='+vec(box.findtext('dimensions'))+';c.shapePosition='+vec(box.findtext('pos'))+';c.centerOfMass='+vec(' '.join(body.findtext('massLocalPose').split()[-3:]))+';c.wheels.clear();', ' c.brakeLimit='+car.findtext('motor/brakeTorque')+';'])
        for source in car.findall('wheels/items/*'):
            shape=source.find('pxActor/shapes/items/item0');lines.append(' {Wheel w;w.position='+vec(source.findtext('pos'))+';')
            for key,path in [('radius','radius'),('travel','suspensionTravel'),('spring','suspension/spring'),('damper','suspension/damper'),('target','suspension/targetValue'),('inverseMass','inverseWheelMass'),('flags','wheelFlags')]:lines.append(' w.'+key+'='+shape.findtext(path)+';')
            lines.append(' w.driven='+source.findtext('lead')+';w.steering='+source.findtext('steer')+';')
            emit_tire('w.longitudinal',shape.find('longitudalTireForceFunction'));emit_tire('w.lateral',shape.find('lateralTireForceFunction'));lines.append(' c.wheels.push_back(w); }')
        lines.append(' {const char* actions[]={"settle","wheel-drive","brake-moving","diagonal-slide","suspension-drop","spin-mixed"};for(int a=0;a<6;++a){Case test=c;test.action=actions[a];test.name=std::string("'+name+'/")+actions[a];if(a!=4)test.height=12;if(a==5){test.ground=false;test.gravity=0;test.height=100;test.angular=V(1,2,3);test.steps=120;}suite.push_back(test);}}')
        # The game replaces database tire curves through Player::ApplyMobility.
        # Cover every available tire upgrade for this car, using an engine-1
        # command in first gear. Engine response/gears are separate gameplay
        # state-machine tests; this fixture directly supplies equal Nm/wheel.
        engine=None
        for func in workshop.findall('engine1/item/carFuncMap/*'):
            if func.findtext('car').split('\\')[-1]==name:engine=func;break
        if engine is None:
            for func in workshop.findall('engine3/item/carFuncMap/*'):
                if func.findtext('car').split('\\')[-1]==name:engine=func;break
        for item in workshop:
            for func in item.findall('item/carFuncMap/*'):
                if func.find('longTire') is None or float(func.findtext('longTire/extremumValue',default='0')) <= 0 or func.findtext('car').split('\\')[-1]!=name:continue
                lines.append(' {Case upgraded=c;upgraded.catalog="'+name+'+'+item.tag+'";upgraded.tireSpring='+func.findtext('tireSpring',default='0')+';upgraded.brakeFactor=upgraded.brakeLimit/4000;')
                if engine is not None:
                    torque=float(engine.findtext('maxTorque'))*2.66*float(car.findtext('motor/gearDiff'))*float(car.findtext('motor/SEM'))*1.15
                    lines.append(' upgraded.torqueFactor='+format(torque/600,'.12g')+';')
                lines.append(' for(size_t w=0;w<upgraded.wheels.size();++w){')
                emit_tire('upgraded.wheels[w].longitudinal',func.find('longTire'));emit_tire('upgraded.wheels[w].lateral',func.find('latTire'));lines.append(' }')
                lines.append(' const char* actions[]={"wheel-drive","brake-moving","diagonal-slide","lateral","suspension-drop"};for(int a=0;a<5;++a){Case test=upgraded;test.action=actions[a];test.name=std::string("mobility/'+name+'/'+item.tag+'/")+actions[a];test.height=a==4?15:12;suite.push_back(test);} }')
    lines.append('}')
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    target=Path(__file__).with_name('Catalog.h');content=generate()
    if a.check:
        if target.read_text()!=content:p.exit(1,'Catalog.h does not match original database/workshop\n')
    else:target.write_text(content)
